module alu #(
    parameter DATA_WIDTH = 8
)(
    input  [DATA_WIDTH-1:0] A,
    input  [DATA_WIDTH-1:0] B,
    input  [3:0] opcode,

    output reg [DATA_WIDTH-1:0] Result,
    output Zero
);

// Temporary register for arithmetic operations
reg [DATA_WIDTH:0] temp;

always @(*) begin

    // Default values
    Result = {DATA_WIDTH{1'b0}};
    temp   = {(DATA_WIDTH+1){1'b0}};

    case(opcode)

        //------------------------------------
        // ADD
        //------------------------------------
        4'b0000:
        begin
            temp   = A + B;
            Result = temp[DATA_WIDTH-1:0];
        end

        //------------------------------------
        // SUB
        //------------------------------------
        4'b0001:
        begin
            temp   = A - B;
            Result = temp[DATA_WIDTH-1:0];
        end

        //------------------------------------
        // AND
        //------------------------------------
        4'b0010:
            Result = A & B;

        //------------------------------------
        // OR
        //------------------------------------
        4'b0011:
            Result = A | B;

        //------------------------------------
        // XOR
        //------------------------------------
        4'b0100:
            Result = A ^ B;

        //------------------------------------
        // NOT
        //------------------------------------
        4'b0101:
            Result = ~A;

        //------------------------------------
        // Shift Left
        //------------------------------------
        4'b0110:
            Result = A << 1;

        //------------------------------------
        // Shift Right
        //------------------------------------
        4'b0111:
            Result = A >> 1;

        //------------------------------------
        // PASS A
        //------------------------------------
        4'b1000:
            Result = A;

        //------------------------------------
        // PASS B
        //------------------------------------
        4'b1001:
            Result = B;

        //------------------------------------
        // Default
        //------------------------------------
        default:
            Result = {DATA_WIDTH{1'b0}};

    endcase

end

//------------------------------------
// Zero Flag
//------------------------------------

assign Zero = (Result == {DATA_WIDTH{1'b0}});

endmodule