`timescale 1ns/1ps

module alu_tb;

parameter DATA_WIDTH = 8;

//-----------------------------------------------------
// Testbench Signals
//-----------------------------------------------------

reg  [DATA_WIDTH-1:0] A;
reg  [DATA_WIDTH-1:0] B;
reg  [3:0] opcode;

wire [DATA_WIDTH-1:0] Result;
wire Zero;

//-----------------------------------------------------
// DUT Instantiation
//-----------------------------------------------------

alu DUT (
    .A(A),
    .B(B),
    .opcode(opcode),
    .Result(Result),
    .Zero(Zero)
);

//-----------------------------------------------------
// Test Sequence
//-----------------------------------------------------

initial begin

    // Initialize
    A = 0;
    B = 0;
    opcode = 0;

    //-------------------------------------------------
    // ADD : 10 + 5 = 15
    //-------------------------------------------------
    #20;
    opcode = 4'b0000;
    A = 8'd10;
    B = 8'd5;

    //-------------------------------------------------
    // SUB : 10 - 5 = 5
    //-------------------------------------------------
    #20;
    opcode = 4'b0001;
    A = 8'd10;
    B = 8'd5;

    //-------------------------------------------------
    // AND
    //-------------------------------------------------
    #20;
    opcode = 4'b0010;
    A = 8'b11001100;
    B = 8'b10101010;

    //-------------------------------------------------
    // OR
    //-------------------------------------------------
    #20;
    opcode = 4'b0011;
    A = 8'b11001100;
    B = 8'b10101010;

    //-------------------------------------------------
    // XOR
    //-------------------------------------------------
    #20;
    opcode = 4'b0100;
    A = 8'b11001100;
    B = 8'b10101010;

    //-------------------------------------------------
    // NOT
    //-------------------------------------------------
    #20;
    opcode = 4'b0101;
    A = 8'b10101010;

    //-------------------------------------------------
    // Shift Left
    //-------------------------------------------------
    #20;
    opcode = 4'b0110;
    A = 8'd4;

    //-------------------------------------------------
    // Shift Right
    //-------------------------------------------------
    #20;
    opcode = 4'b0111;
    A = 8'd8;

    //-------------------------------------------------
    // PASS A
    //-------------------------------------------------
    #20;
    opcode = 4'b1000;
    A = 8'd55;

    //-------------------------------------------------
    // PASS B
    //-------------------------------------------------
    #20;
    opcode = 4'b1001;
    B = 8'd99;

    //-------------------------------------------------
    // Zero Flag Test
    //-------------------------------------------------
    #20;
    opcode = 4'b0001;
    A = 8'd5;
    B = 8'd5;

    //-------------------------------------------------

    #20;
    $finish;

end

//-----------------------------------------------------
// Monitor
//-----------------------------------------------------

initial begin
    $monitor("Time=%0t Opcode=%b A=%d B=%d Result=%d Zero=%b",
             $time, opcode, A, B, Result, Zero);
end

//-----------------------------------------------------
// Waveform Dump
//-----------------------------------------------------

initial begin
    $dumpfile("waveforms/alu.vcd");
    $dumpvars(0, alu_tb);
end

endmodule