`timescale 1ns/1ps

module control_unit_tb;

reg [3:0] opcode;
reg [7:0] pc;

wire reg_write;
wire pc_write;
wire halt;
wire [3:0] alu_op;
wire [7:0] pc_next;

//-----------------------------------------------------
// DUT
//-----------------------------------------------------

control_unit DUT (
    .opcode(opcode),
    .pc(pc),
    .reg_write(reg_write),
    .pc_write(pc_write),
    .halt(halt),
    .alu_op(alu_op),
    .pc_next(pc_next)
);

//-----------------------------------------------------
// Test Sequence
//-----------------------------------------------------

initial begin

    // Initialize
    opcode = 4'b0000;
    pc     = 8'd0;

    //-------------------------------------------------
    // ADD
    //-------------------------------------------------
    #20;
    opcode = 4'b0000;
    pc = 8'd0;

    //-------------------------------------------------
    // SUB
    //-------------------------------------------------
    #20;
    opcode = 4'b0001;
    pc = 8'd1;

    //-------------------------------------------------
    // AND
    //-------------------------------------------------
    #20;
    opcode = 4'b0010;
    pc = 8'd2;

    //-------------------------------------------------
    // OR
    //-------------------------------------------------
    #20;
    opcode = 4'b0011;
    pc = 8'd3;

    //-------------------------------------------------
    // XOR
    //-------------------------------------------------
    #20;
    opcode = 4'b0100;
    pc = 8'd4;

    //-------------------------------------------------
    // NOT
    //-------------------------------------------------
    #20;
    opcode = 4'b0101;
    pc = 8'd5;

    //-------------------------------------------------
    // SHL
    //-------------------------------------------------
    #20;
    opcode = 4'b0110;
    pc = 8'd6;

    //-------------------------------------------------
    // SHR
    //-------------------------------------------------
    #20;
    opcode = 4'b0111;
    pc = 8'd7;

    //-------------------------------------------------
    // LOADI
    //-------------------------------------------------
    #20;
    opcode = 4'b1000;
    pc = 8'd8;

    //-------------------------------------------------
    // HALT
    //-------------------------------------------------
    #20;
    opcode = 4'b1001;
    pc = 8'd9;

    //-------------------------------------------------
    // Invalid Opcode
    //-------------------------------------------------
    #20;
    opcode = 4'b1111;
    pc = 8'd10;

    #20;
    $finish;

end

//-----------------------------------------------------
// Monitor
//-----------------------------------------------------

initial begin
    $monitor(
        "Time=%0t Opcode=%b PC=%0d | RegWrite=%b PCWrite=%b Halt=%b ALUOp=%b PCNext=%0d",
        $time,
        opcode,
        pc,
        reg_write,
        pc_write,
        halt,
        alu_op,
        pc_next
    );
end

//-----------------------------------------------------
// Waveform Dump
//-----------------------------------------------------

initial begin
    $dumpfile("waveforms/control_unit.vcd");
    $dumpvars(0, control_unit_tb);
end

endmodule